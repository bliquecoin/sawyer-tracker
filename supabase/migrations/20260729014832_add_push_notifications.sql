create extension if not exists pg_cron with schema pg_catalog;
create extension if not exists pg_net with schema extensions;

create table if not exists public.sawyer_push_subscriptions (
  id uuid primary key default gen_random_uuid(),
  household_id uuid not null references public.sawyer_households(id) on delete cascade,
  device_id text not null,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  timezone text not null default 'Australia/Brisbane',
  user_agent text not null default '',
  enabled boolean not null default true,
  failure_count integer not null default 0,
  last_success_at timestamptz,
  last_failure_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint sawyer_push_subscriptions_device_unique unique (household_id, device_id),
  constraint sawyer_push_subscriptions_device_id_length check (char_length(device_id) between 8 and 128),
  constraint sawyer_push_subscriptions_endpoint_https check (endpoint like 'https://%'),
  constraint sawyer_push_subscriptions_timezone_length check (char_length(timezone) between 1 and 80),
  constraint sawyer_push_subscriptions_failure_count_nonnegative check (failure_count >= 0)
);

create table if not exists public.sawyer_push_deliveries (
  id bigint generated by default as identity primary key,
  household_id uuid not null references public.sawyer_households(id) on delete cascade,
  subscription_id uuid not null references public.sawyer_push_subscriptions(id) on delete cascade,
  event_key text not null,
  kind text not null,
  target_at timestamptz not null,
  status text not null default 'pending',
  title text not null,
  body text not null,
  attempt_count integer not null default 0,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  sent_at timestamptz,
  constraint sawyer_push_deliveries_once unique (subscription_id, event_key),
  constraint sawyer_push_deliveries_kind check (kind in ('heart', 'longest_streak', 'average_gap')),
  constraint sawyer_push_deliveries_status check (status in ('pending', 'sent', 'failed')),
  constraint sawyer_push_deliveries_attempt_count_nonnegative check (attempt_count >= 0)
);

create index if not exists sawyer_push_subscriptions_household_enabled_idx
  on public.sawyer_push_subscriptions (household_id, enabled);

create index if not exists sawyer_push_deliveries_household_created_idx
  on public.sawyer_push_deliveries (household_id, created_at desc);

alter table public.sawyer_push_subscriptions enable row level security;
alter table public.sawyer_push_deliveries enable row level security;

revoke all on public.sawyer_push_subscriptions from public, anon, authenticated;
revoke all on public.sawyer_push_deliveries from public, anon, authenticated;
revoke all on sequence public.sawyer_push_deliveries_id_seq from public, anon, authenticated;

